#!/usr/bin/env node
// The audit pack's generated pages (Stage 11). Run with tsx (the schema is TypeScript):
//
//   npm run audit:pack          write docs/audit/{DATA-MODEL,TEST-INVENTORY,DEPENDENCIES}.md and the copies
//   npm run audit:pack:check    fail when any of them is out of date (the watcher runs it)
//
// Copies: FIELD-TRACE, SCREEN-FLOW, KNOWN-GAPS and RULES (docs/GST-RULES.md) are copied from docs/
// with a line saying where they come from, so the auditor reads one folder. DEPENDENCIES lists every
// workspace's direct dependencies with the licence their package declares; `npm audit` is recorded by
// `npm run audit:deps` into docs/audit/npm-audit.json (it needs the registry, so it is not part of
// --check). COVERAGE.md is written by `npm run audit:coverage`.
import { existsSync, readFileSync, readdirSync, statSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

import { getTableConfig } from 'drizzle-orm/pg-core';
import * as prettier from 'prettier';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(ROOT, 'docs', 'audit');
const check = process.argv.includes('--check');
const files = new Map();
const GENERATED = (from) =>
  `<!-- Generated by \`npm run audit:pack\`${from ? ` from ${from}` : ''}. Do not edit by hand. -->`;

// --- DATA-MODEL.md: every table from the Drizzle schema ---------------------------------------
const schema = await import(join(ROOT, 'packages/db/src/schema.ts'));
// Tables whose rows belong to one business and carry forced RLS (apply_tenancy or the ai_calls policy).
const tenancyText = readdirSync(join(ROOT, 'packages/db/migrations'))
  .filter((f) => f.endsWith('.sql'))
  .map((f) => readFileSync(join(ROOT, 'packages/db/migrations', f), 'utf8'))
  .join('\n');
const rlsTables = new Set(
  [...tenancyText.matchAll(/apply_tenancy\('([a-z_]+)'(?:,\s*(true|false))?/g)]
    .filter((m) => m[2] !== 'false')
    .map((m) => m[1]),
);
for (const m of tenancyText.matchAll(/alter table ([a-z_]+) force row level security/g)) rlsTables.add(m[1]);
// Row-level security switched on without FORCE (the table owner is not bound): audit_events, read per business.
const rlsOnly = new Set(
  [...tenancyText.matchAll(/alter table ([a-z_]+) enable row level security/g)]
    .map((m) => m[1])
    .filter((t) => !rlsTables.has(t)),
);
const auditedTables = new Set([...tenancyText.matchAll(/apply_tenancy\('([a-z_]+)'/g)].map((m) => m[1]));
for (const m of tenancyText.matchAll(/drop trigger if exists audit on ([a-z_]+);\s*$/gm)) {
  // A table whose audit trigger is dropped and not re-created afterwards is not audited.
  const after = tenancyText.slice(m.index + m[0].length);
  if (!new RegExp(`create trigger audit after insert or update on ${m[1]}\\b`).test(after)) auditedTables.delete(m[1]);
}
const tables = Object.values(schema)
  .filter((v) => v && typeof v === 'object' && Symbol.for('drizzle:IsDrizzleTable') in v)
  .map((t) => getTableConfig(t))
  .sort((a, b) => a.name.localeCompare(b.name));
const dm = [
  '# Data model',
  '',
  GENERATED('packages/db/src/schema.ts and the migrations'),
  '',
  `${tables.length} tables. Money is integer paise (\`bigint\`), percentages basis points, dates civil dates (\`date\`), times \`timestamptz\`. **RLS**: \`forced\` is row-level security on the business column that binds the table owner too (I1); \`on\` binds the application role only. **Audit**: one \`audit_events\` row per insert and update (I7). Every business table also refuses deletes (8.3) and model writes (I6), except where a migration says otherwise.`,
  '',
  '| Table | Columns | RLS | Audit |',
  '| --- | --- | --- | --- |',
  ...tables.map(
    (t) =>
      `| [\`${t.name}\`](#${t.name.replace(/_/g, '_')}) | ${t.columns.length} | ${rlsTables.has(t.name) ? 'forced' : rlsOnly.has(t.name) ? 'on' : 'no'} | ${auditedTables.has(t.name) ? 'yes' : 'no'} |`,
  ),
  '',
];
for (const t of tables) {
  dm.push(`## ${t.name}`, '', '| Column | Type | Null | Default |', '| --- | --- | --- | --- |');
  for (const c of t.columns) {
    const sqlText = (d) =>
      d.queryChunks
        .map((ch) => (Array.isArray(ch?.value) ? ch.value.join('') : typeof ch === 'string' ? ch : ''))
        .join('');
    const def = c.generated
      ? 'generated'
      : c.hasDefault
        ? c.default === undefined
          ? 'generated'
          : c.default?.queryChunks
            ? sqlText(c.default)
            : typeof c.default === 'object'
              ? JSON.stringify(c.default)
              : String(c.default)
        : '';
    dm.push(`| \`${c.name}\` | ${c.getSQLType()} | ${c.notNull ? 'no' : 'yes'} | ${def.replace(/\|/g, '\\|')} |`);
  }
  const fks = t.foreignKeys.map((fk) => {
    const r = fk.reference();
    return `\`${r.columns.map((c) => c.name).join(', ')}\` → \`${getTableConfig(r.foreignTable).name}\``;
  });
  if (fks.length) dm.push('', `References: ${fks.join('; ')}.`);
  if (t.indexes.length)
    dm.push(
      '',
      `Indexes: ${t.indexes.map((i) => `\`${i.config.name}\`${i.config.unique ? ' (unique)' : ''}`).join(', ')}.`,
    );
  if (t.checks.length) dm.push('', `Checks: ${t.checks.map((c) => `\`${c.name}\``).join(', ')}.`);
  dm.push('');
}
files.set('DATA-MODEL.md', dm.join('\n'));

// --- TEST-INVENTORY.md: every test by file ----------------------------------------------------
function walk(dir, out = []) {
  for (const name of readdirSync(dir)) {
    if (name === 'node_modules' || name.startsWith('.') || name === '__screenshots__') continue;
    const p = join(dir, name);
    if (statSync(p).isDirectory()) walk(p, out);
    else if (/\.(test|spec)\.ts$/.test(name)) out.push(p);
  }
  return out;
}
const testFiles = [...walk(join(ROOT, 'tests')), ...walk(join(ROOT, 'packages'))].sort();
const suites = { unit: [], integration: [], e2e: [], other: [] };
for (const f of testFiles) {
  const rel = relative(ROOT, f);
  const text = readFileSync(f, 'utf8');
  const titles = [...text.matchAll(/^\s*(?:it|test)(?:\.each\([^)]*\))?\(\s*(['`"])((?:\\.|(?!\1).)*)\1/gm)].map(
    (m) => m[2],
  );
  const generated = /^\s*for \(const /m.test(text) && /test\(`|it\(`/.test(text);
  const kind =
    rel.startsWith('tests/unit') || rel.startsWith('packages')
      ? 'unit'
      : rel.startsWith('tests/integration')
        ? 'integration'
        : rel.startsWith('tests/e2e')
          ? 'e2e'
          : 'other';
  suites[kind].push({ rel, titles, generated });
}
const inv = ['# Test inventory', '', GENERATED('the test files'), ''];
inv.push(
  'Counts are the test titles written in each file; a title inside a loop (marked ×) runs once per case, so the runner reports more. The last full runs are in the stage reports.',
  '',
  '| Suite | Files | Titles |',
  '| --- | --- | --- |',
);
for (const [k, list] of Object.entries(suites))
  if (list.length) inv.push(`| ${k} | ${list.length} | ${list.reduce((s, f) => s + f.titles.length, 0)} |`);
inv.push('');
for (const [k, list] of Object.entries(suites)) {
  if (!list.length) continue;
  inv.push(`## ${k}`, '');
  for (const f of list) {
    inv.push(`### \`${f.rel}\`${f.generated ? ' ×' : ''}`, '');
    for (const t of f.titles) inv.push(`- ${t.replace(/\$\{[^}]*\}/g, '…')}`);
    inv.push('');
  }
}
files.set('TEST-INVENTORY.md', inv.join('\n'));

// --- DEPENDENCIES.md: direct dependencies and their licences -----------------------------------
function licenceOf(name) {
  for (const base of [ROOT, join(ROOT, 'apps/web'), join(ROOT, 'apps/worker')]) {
    const p = join(base, 'node_modules', name, 'package.json');
    if (existsSync(p)) {
      const pkg = JSON.parse(readFileSync(p, 'utf8'));
      return {
        version: pkg.version,
        licence: typeof pkg.license === 'string' ? pkg.license : (pkg.license?.type ?? '—'),
      };
    }
  }
  return { version: 'not installed', licence: '—' };
}
const workspaces = [
  '.',
  'apps/web',
  'apps/worker',
  'packages/db',
  'packages/engine',
  'packages/ai',
  'packages/ui',
  'packages/render',
  'packages/copy',
  'design',
];
const deps = ['# Dependencies', '', GENERATED("the workspaces' package.json"), ''];
deps.push(
  'Every direct dependency of every workspace, the version installed and the licence its package declares. The Urbanist typeface (design/fonts) is under the SIL Open Font License 1.1 (`design/fonts/OFL-LICENSE.txt`). `npm audit` is in `npm-audit.json` (`npm run audit:deps`).',
  '',
);
const seen = new Map();
for (const w of workspaces) {
  const p = join(ROOT, w, 'package.json');
  if (!existsSync(p)) continue;
  const pkg = JSON.parse(readFileSync(p, 'utf8'));
  for (const [kind, list] of [
    ['runtime', pkg.dependencies ?? {}],
    ['dev', pkg.devDependencies ?? {}],
  ])
    for (const [name, range] of Object.entries(list)) {
      if (name.startsWith('@ekbill/')) continue;
      const key = `${name}|${kind}`;
      const e = seen.get(key) ?? { name, kind, range, workspaces: [] };
      e.workspaces.push(w === '.' ? 'root' : w);
      seen.set(key, e);
    }
}
deps.push('| Package | Kind | Wanted | Installed | Licence | Used by |', '| --- | --- | --- | --- | --- | --- |');
for (const e of [...seen.values()].sort((a, b) => a.kind.localeCompare(b.kind) || a.name.localeCompare(b.name))) {
  const l = licenceOf(e.name);
  deps.push(`| \`${e.name}\` | ${e.kind} | ${e.range} | ${l.version} | ${l.licence} | ${e.workspaces.join(', ')} |`);
}
const licences = [...new Set([...seen.values()].map((e) => licenceOf(e.name).licence))].sort();
deps.push('', `Licences in use: ${licences.join(', ')}.`, '');
const auditFile = join(OUT, 'npm-audit.json');
if (existsSync(auditFile)) {
  const a = JSON.parse(readFileSync(auditFile, 'utf8'));
  const v = a.metadata?.vulnerabilities ?? {};
  deps.push(
    '## npm audit',
    '',
    `Recorded ${a.recordedAt ?? 'unknown'}: ${['critical', 'high', 'moderate', 'low', 'info'].map((s) => `${s} ${v[s] ?? 0}`).join(', ')}.`,
    '',
  );
  for (const [name, x] of Object.entries(a.vulnerabilities ?? {}).sort())
    deps.push(
      `- \`${name}\` (${x.severity}): ${[...new Set((x.via ?? []).map((y) => (typeof y === 'string' ? y : y.title)))].join('; ')}${x.fixAvailable ? '' : ' — no fix available'}`,
    );
  deps.push('');
}
files.set('DEPENDENCIES.md', deps.join('\n'));

// --- REVIEWS.md: every stage's report and independent review rounds ------------------------------
const stagesDir = join(ROOT, 'docs', 'stages');
const stageFiles = readdirSync(stagesDir).filter((f) => f.endsWith('.md'));
const stageNos = [
  ...new Set(stageFiles.map((f) => Number(/^stage-(\d+)-/.exec(f)?.[1])).filter((n) => !Number.isNaN(n))),
].sort((a, b) => a - b);
const rv = ['# Reviews', '', GENERATED('docs/stages'), ''];
rv.push(
  "Rule 12: every stage is reviewed by an independent OpenAI model on the VM (`npm run review:stage -- N`), and its findings are answered in the next round, the stage's answers file or the next stage's report. A stage with no review file has not been reviewed yet.",
  '',
  '| Stage | Report | Review rounds | Last verdict |',
  '| --- | --- | --- | --- |',
);
const fieldOf = (text, name) => new RegExp(`^- ${name}: (.+)$`, 'm').exec(text)?.[1]?.trim() ?? '—';
for (const n of stageNos) {
  const reviews = stageFiles.filter((f) => new RegExp(`^stage-${n}-review-\\d+\\.md$`).test(f)).sort();
  const report = stageFiles.includes(`stage-${n}-report.md`) ? `[report](../stages/stage-${n}-report.md)` : '—';
  const last = reviews.length
    ? fieldOf(readFileSync(join(stagesDir, reviews.at(-1)), 'utf8'), 'Verdict')
    : 'not reviewed yet';
  rv.push(`| ${n} | ${report} | ${reviews.length} | ${last} |`);
}
rv.push('');
for (const n of stageNos) {
  const reviews = stageFiles.filter((f) => new RegExp(`^stage-${n}-review-\\d+\\.md$`).test(f)).sort();
  const answers = stageFiles.filter((f) => new RegExp(`^stage-${n}-answers\\.md$`).test(f));
  if (!reviews.length && !answers.length) continue;
  rv.push(`## Stage ${n}`, '');
  for (const f of reviews) {
    const t = readFileSync(join(stagesDir, f), 'utf8');
    rv.push(
      `- [${f}](../stages/${f}): commit ${fieldOf(t, 'Reviewed commit')}, ${fieldOf(t, 'At').slice(0, 10)}, verdict **${fieldOf(t, 'Verdict')}**`,
    );
  }
  for (const f of answers) rv.push(`- [${f}](../stages/${f}): the answers to the review`);
  rv.push('');
}
files.set('REVIEWS.md', rv.join('\n'));

// --- copies of the living documents --------------------------------------------------------------
for (const [to, from] of [
  ['FIELD-TRACE.md', 'docs/FIELD-TRACE.md'],
  ['SCREEN-FLOW.md', 'docs/SCREEN-FLOW.md'],
  ['KNOWN-GAPS.md', 'docs/KNOWN-GAPS.md'],
  ['RULES.md', 'docs/GST-RULES.md'],
]) {
  const text = readFileSync(join(ROOT, from), 'utf8');
  files.set(to, `${GENERATED(from)}\n\n${text}`);
}

// --- write or check ----------------------------------------------------------------------------------
mkdirSync(OUT, { recursive: true });
const stale = [];
for (const [name, text] of files) {
  const p = join(OUT, name);
  // Formatted as the repository formats markdown, so format:check and this check agree.
  const body = await prettier.format(text, { ...(await prettier.resolveConfig(p)), filepath: p });
  if (check) {
    if (!existsSync(p) || readFileSync(p, 'utf8') !== body) stale.push(name);
  } else writeFileSync(p, body);
}
if (check) {
  if (stale.length) {
    console.error(`audit:pack:check: out of date: ${stale.join(', ')}; run npm run audit:pack`);
    process.exit(1);
  }
  console.log(`audit:pack:check: ${files.size} pages current`);
} else console.log(`audit:pack: wrote ${[...files.keys()].join(', ')} in docs/audit`);
