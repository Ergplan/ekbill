#!/usr/bin/env node
// The rule-update workflow (Stage 8, I5).
//
//   npm run rules:update          list every entry: id, window, verified or not, when, source
//   npm run rules:doc             regenerate docs/GST-RULES.md from the pack
//   npm run rules:doc:check       fail when docs/GST-RULES.md is out of date (the watcher runs it)
//
// The workflow when a rule changes (a notification, a Council decision):
//   1. npm run rules:update shows the entry and its source; read the source.
//   2. Never edit a verified entry: add a new entry with the new effectiveFrom
//      (and close the old one's effectiveTo the day before).
//   3. Bump the file's "version" (YYYY.MM.DD-<what>), add a fixture dated inside
//      and outside the new window (tests/unit/engine-rules.test.ts).
//   4. npm run rules:verify where the official sites are reachable (the VM),
//      npm run rules:check, npm run rules:doc, commit.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const DIR = join(ROOT, 'packages/engine/rules/gst');
const DOC = join(ROOT, 'docs/GST-RULES.md');
const mode = process.argv.includes('--doc') ? 'doc' : process.argv.includes('--check') ? 'check' : 'list';

const packs = readdirSync(DIR)
  .filter((f) => f.endsWith('.json') && f !== 'hsn-index.json')
  .sort()
  .map((file) => ({ file, ...JSON.parse(readFileSync(join(DIR, file), 'utf8')) }));

if (mode === 'list') {
  for (const p of packs) {
    console.log(`\n${p.file}  (version ${p.version})`);
    for (const e of p.entries)
      console.log(
        `  ${e.verified ? 'verified  ' : 'UNVERIFIED'}  ${e.id.padEnd(30)} ${e.effectiveFrom} → ${e.effectiveTo ?? 'open'}  checked ${e.verifiedOn}\n              ${e.source}`,
      );
  }
  const all = packs.flatMap((p) => p.entries);
  console.log(`\n${all.length} entries, ${all.filter((e) => !e.verified).length} unverified (at most 3 may stay so).`);
  process.exit(0);
}

const esc = (s) => String(s ?? '').replace(/\|/g, '\\|');
const lines = [
  '# GST rules',
  '',
  '<!-- Generated by `npm run rules:doc` from packages/engine/rules/gst/*.json. Do not edit by hand. -->',
  '',
  'The rules EkBill applies, as the rule pack holds them (I5): every entry with the window it applies in, the official source, whether that source was checked, and the explanation the app shows when the owner taps "Kyun?". The engine reads only the pack; a rule that changes is a new entry with a new date, never an edit.',
  '',
];
for (const p of packs) {
  lines.push(`## ${p.file.replace(/\.json$/, '')} (version ${p.version})`, '');
  lines.push('| Entry | Applies | Checked | Explanation | Source |', '| --- | --- | --- | --- | --- |');
  for (const e of p.entries)
    lines.push(
      `| \`${e.id}\` | ${e.effectiveFrom} to ${e.effectiveTo ?? 'now'} | ${e.verified ? `yes, ${e.verifiedOn}` : `not yet (${e.verifiedOn})`} | ${esc(e.explain?.en)} | ${esc(e.source)} |`,
    );
  lines.push('');
}
lines.push(
  '## For the CA: what the pack does not hold',
  '',
  'These are outside what EkBill decides, written here so the CA knows where the app stops.',
  '',
  '- **Invoice Management System (IMS).** From October 2024 a recipient accepts, rejects or keeps pending the invoices its suppliers report; the accepted ones flow into its GSTR-2B and its input tax credit. EkBill reports the supplier side (GSTR-1) only; a customer rejecting an invoice in IMS is not seen by the app. The CA follows it on the portal.',
  '- **E-way bill.** A consignment of goods worth more than ₹50,000 moved by road needs an e-way bill (the state limit for movement inside some states differs). EkBill does not generate e-way bills; the owner or the CA generates them on the e-way bill portal with the invoice number EkBill issued.',
  '- **Registration thresholds.** Aggregate turnover above ₹40 lakh (goods) or ₹20 lakh (services) makes registration compulsory (₹20 lakh and ₹10 lakh in the special category states); inter-State supply of goods needs registration whatever the turnover. EkBill asks the owner whether they are registered and does not decide it.',
  '- **Purchases and input tax credit.** GSTR-2B reconciliation, ITC and the credit side of GSTR-3B are not in this release; the CA pack carries the outward side only.',
  '',
);
const text = `${lines.join('\n')}`;
if (mode === 'check') {
  let current;
  try {
    current = readFileSync(DOC, 'utf8');
  } catch {
    current = '';
  }
  if (current !== text) {
    console.error('rules:doc:check: docs/GST-RULES.md is out of date; run npm run rules:doc');
    process.exit(1);
  }
  console.log(`rules:doc:check: ${packs.reduce((s, p) => s + p.entries.length, 0)} entries, document current`);
} else {
  writeFileSync(DOC, text);
  console.log(`wrote docs/GST-RULES.md (${packs.reduce((s, p) => s + p.entries.length, 0)} entries)`);
}
