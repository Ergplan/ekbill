#!/usr/bin/env node
// gen:tests — the generated integration tests (I1, I8):
//   tests/integration/tenancy.test.ts  from the repository module list (packages/db/src/repos/index.ts):
//                                      every module's tenancyProbes run as business A against business B.
//   tests/integration/roles.test.ts    from every module's allowedRoles: each write, each role, allowed or forbidden.
// `--check` fails when the committed files differ from what the sources say (the watcher runs it).
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import prettier from 'prettier';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const REPOS = join(ROOT, 'packages/db/src/repos');
const check = process.argv.includes('--check');

const index = readFileSync(join(REPOS, 'index.ts'), 'utf8');
const list = index.match(/REPOSITORIES = \[([^\]]*)\]/);
if (!list) {
  console.error('gen:tests: packages/db/src/repos/index.ts has no REPOSITORIES list');
  process.exit(2);
}
const modules = [...list[1].matchAll(/'([a-z-]+)'/g)].map((m) => m[1]).sort();

/** `export const allowedRoles = { name: ['owner', 'staff'], ... }` → [{ name, roles }] */
function allowedRolesOf(source, mod) {
  const m = source.match(/export const allowedRoles = \{([\s\S]*?)\} as const/);
  if (!m) {
    console.error(`gen:tests: ${mod}.ts has no allowedRoles`);
    process.exit(2);
  }
  return [...m[1].matchAll(/(\w+):\s*\[([^\]]*)\]/g)].map((x) => ({
    name: x[1],
    roles: [...x[2].matchAll(/'(\w+)'/g)].map((r) => r[1]),
  }));
}
/** tenancyProbes entries' names, in order */
function tenancyProbesOf(source, mod) {
  const m = source.match(/export const tenancyProbes: TenancyProbe\[\] = \[([\s\S]*)\];/);
  if (!m) {
    console.error(`gen:tests: ${mod}.ts has no tenancyProbes`);
    process.exit(2);
  }
  // A probe is { name, run }: only a name followed by its run counts (a file's name inside a probe does not).
  return [...m[1].matchAll(/name:\s*(['"])(.*?)\1,\s*run:/g)].map((x) => x[2]);
}

const ROLES = ['owner', 'staff', 'accountant'];
const header = (what) =>
  `// GENERATED by scripts/gen-tests.mjs (${what}). Do not edit: change the repository and run npm run gen:tests.\n`;

const sources = Object.fromEntries(modules.map((m) => [m, readFileSync(join(REPOS, `${m}.ts`), 'utf8')]));

const roles = [
  header('from allowedRoles in packages/db/src/repos/*.ts — I8: roles are enforced at the repository'),
  "import { describe, expect, it } from 'vitest';",
  '',
  "import { ForbiddenError } from '../../packages/db/src/repos/allow';",
  // A read-only module (no writes, e.g. gst) has nothing to test here.
  ...modules
    .filter((m) => allowedRolesOf(sources[m], m).length)
    .map((m) => `import * as ${m.replace(/-/g, '_')} from '../../packages/db/src/repos/${m}';`),
  "import { scopeFor, seeded } from './helpers';",
  '',
  "describe('roles (I8): every repository write, every role', () => {",
  '  seeded();',
];
for (const mod of modules) {
  const id = mod.replace(/-/g, '_');
  for (const { name, roles: allowed } of allowedRolesOf(sources[mod], mod)) {
    for (const role of ROLES) {
      const ok = allowed.includes(role);
      roles.push(
        `  it('${mod}.${name}: ${role} ${ok ? 'may' : 'may not'}', async () => {`,
        `    const scope = await scopeFor('sharma', '${role}');`,
        ok
          ? `    await expect(${id}.roleProbes.${name}(scope)).resolves.toBeDefined();`
          : `    await expect(${id}.roleProbes.${name}(scope)).rejects.toBeInstanceOf(ForbiddenError);`,
        '  });',
      );
    }
  }
}
roles.push('});', '');

const tenancy = [
  header(
    'from the repository module list in packages/db/src/repos/index.ts — I1: scope A sees and changes nothing of B',
  ),
  "import { describe, expect, it } from 'vitest';",
  '',
  ...modules.map((m) => `import * as ${m.replace(/-/g, '_')} from '../../packages/db/src/repos/${m}';`),
  "import { otherBusiness, scopeFor, seeded } from './helpers';",
  '',
  "describe('tenancy (I1): every repository, business A against business B', () => {",
  '  seeded();',
];
for (const mod of modules) {
  const id = mod.replace(/-/g, '_');
  tenancyProbesOf(sources[mod], mod).forEach((name, i) => {
    tenancy.push(
      `  it(${JSON.stringify(`${mod}: ${name}`)}, async () => {`,
      `    const a = await scopeFor('sharma', 'owner');`,
      `    const b = await otherBusiness('gupta');`,
      `    const { touched } = await ${id}.tenancyProbes[${i}]!.run(a, b);`,
      `    expect(touched).not.toContain(b.businessId);`,
      `    for (const id of touched) expect(id).toBe(a.businessId);`,
      '  });',
    );
  });
}
tenancy.push('});', '');

const outputs = {
  'tests/integration/roles.test.ts': roles.join('\n'),
  'tests/integration/tenancy.test.ts': tenancy.join('\n'),
};
let drift = false;
for (const [rel, raw] of Object.entries(outputs)) {
  const path = join(ROOT, rel);
  // Written the way prettier would, so the committed file and the check agree.
  const text = await prettier.format(raw, { ...(await prettier.resolveConfig(path)), filepath: path });
  const current = existsSync(path) ? readFileSync(path, 'utf8') : null;
  if (check) {
    if (current !== text) {
      console.error(`gen:check: ${rel} is out of date (run npm run gen:tests)`);
      drift = true;
    }
  } else {
    writeFileSync(path, text);
    console.log(`wrote ${rel}`);
  }
}
if (check) {
  if (drift) process.exit(1);
  console.log('gen:check: generated tests are current');
}
