#!/usr/bin/env node
// FIELD-TRACE (master prompt 5.3): every Drizzle table and column, and every
// zod input field, with its owner. Generated into docs/FIELD-TRACE.md.
//
//   npm run trace          # regenerate
//   npm run trace:check    # fail on drift, or on an input field with no owner
//
// Owner of a zod field = the Drizzle column of the same name in the table the
// schema file names in a comment "// table: <name>", or an entry in
// docs/field-owners.json (field → where it ends up, e.g. "derived: engine").
// Sources: packages/db/src/schema.ts (pgTable literals) and every
// **/schema.ts under apps/web and packages/engine (z.object literals).
// A schema file that validates data files rather than user input (the rule
// pack's packages/engine/rules/schema.ts) opts out with "// trace: not-input".
import { existsSync, readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(ROOT, 'docs', 'FIELD-TRACE.md');
const check = process.argv.includes('--check');

function* walk(dir, match) {
  if (!existsSync(dir)) return;
  for (const entry of readdirSync(dir)) {
    if (['node_modules', '.next', 'dist'].includes(entry)) continue;
    const full = join(dir, entry);
    if (statSync(full).isDirectory()) yield* walk(full, match);
    else if (match(full)) yield full;
  }
}

/** pgTable('name', { col: type(...), ... }) → [{ table, columns }] */
function drizzleTables(source) {
  const tables = [];
  const re = /pgTable\(\s*['"]([a-z_]+)['"]\s*,\s*\{/g;
  let m;
  while ((m = re.exec(source))) {
    const start = re.lastIndex;
    let depth = 1;
    let i = start;
    while (i < source.length && depth > 0) {
      if (source[i] === '{') depth += 1;
      else if (source[i] === '}') depth -= 1;
      i += 1;
    }
    const body = source.slice(start, i - 1);
    const columns = [...body.matchAll(/^\s*([a-zA-Z_][a-zA-Z0-9_]*)\s*:/gm)].map((c) => c[1]);
    tables.push({ table: m[1], columns });
  }
  return tables;
}

/** export const X = z.object({ field: ..., }) → [{ name, fields }] */
function zodSchemas(source) {
  const out = [];
  const re = /export const ([A-Za-z0-9_]+)\s*=\s*z\s*\.object\(\s*\{/g;
  let m;
  while ((m = re.exec(source))) {
    const start = re.lastIndex;
    let depth = 1;
    let i = start;
    while (i < source.length && depth > 0) {
      if (source[i] === '{') depth += 1;
      else if (source[i] === '}') depth -= 1;
      i += 1;
    }
    const body = source.slice(start, i - 1);
    const fields = [...body.matchAll(/^\s*([a-zA-Z_][a-zA-Z0-9_]*)\s*:/gm)].map((c) => c[1]);
    out.push({ name: m[1], fields });
  }
  return out;
}

const dbSchema = join(ROOT, 'packages/db/src/schema.ts');
const tables = existsSync(dbSchema) ? drizzleTables(readFileSync(dbSchema, 'utf8')) : [];
const columns = new Map(tables.map((t) => [t.table, new Set(t.columns)]));

let owners = {};
const ownersPath = join(ROOT, 'docs', 'field-owners.json');
if (existsSync(ownersPath)) owners = JSON.parse(readFileSync(ownersPath, 'utf8'));

const inputs = [];
const orphans = [];
for (const dir of ['apps/web', 'packages/engine', 'packages/ai']) {
  for (const file of walk(join(ROOT, dir), (f) => /(^|\/)schema\.ts$/.test(f) || /\.schema\.ts$/.test(f))) {
    const source = readFileSync(file, 'utf8');
    if (/\/\/\s*trace:\s*not-input/.test(source)) continue;
    const table = source.match(/\/\/\s*table:\s*([a-z_]+)/)?.[1] ?? null;
    for (const s of zodSchemas(source)) {
      const rel = relative(ROOT, file);
      for (const field of s.fields) {
        const key = `${s.name}.${field}`;
        let owner = null;
        if (table && columns.get(table)?.has(field)) owner = `${table}.${field}`;
        else if (owners[key]) owner = owners[key];
        else if (owners[field]) owner = owners[field];
        inputs.push({ schema: s.name, field, file: rel, owner });
        if (!owner) orphans.push(`${rel}: ${key}`);
      }
    }
  }
}

const lines = [
  '# Field trace',
  '',
  'Generated by `scripts/trace.mjs`; do not edit. Every Drizzle column and every zod input field with its owner.',
  '`npm run trace:check` fails on drift or on an input field that no column or `docs/field-owners.json` entry owns.',
  '',
  '## Tables (packages/db/src/schema.ts)',
  '',
];
if (!tables.length) lines.push('_No tables yet. Stage 2 adds identity, tenancy, roles, audit and `ai_calls`._', '');
for (const t of tables) {
  lines.push(`### ${t.table}`, '', ...t.columns.map((c) => `- ${c}`), '');
}
lines.push('## Input fields (zod schemas)', '');
if (!inputs.length)
  lines.push('_No input schemas yet. Stage 1 adds the screen manifests; Stage 4 onward add server-action inputs._', '');
else {
  lines.push('| Schema | Field | File | Owner |', '| --- | --- | --- | --- |');
  for (const i of inputs) lines.push(`| ${i.schema} | ${i.field} | ${i.file} | ${i.owner ?? '**none**'} |`);
  lines.push('');
}
const doc = `${lines.join('\n')}\n`;

if (check) {
  const current = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';
  let failed = false;
  if (current !== doc) {
    console.error('trace:check: docs/FIELD-TRACE.md is out of date; run npm run trace');
    failed = true;
  }
  if (orphans.length) {
    console.error('trace:check: input fields with no owner:');
    for (const o of orphans) console.error(`  ${o}`);
    failed = true;
  }
  if (failed) process.exit(1);
  console.log(`trace:check: ${tables.length} table(s), ${inputs.length} input field(s), all owned, document current`);
} else {
  writeFileSync(OUT, doc);
  console.log(`wrote docs/FIELD-TRACE.md (${tables.length} table(s), ${inputs.length} input field(s))`);
  if (orphans.length) {
    console.error(`${orphans.length} field(s) without an owner (trace:check will fail):`);
    for (const o of orphans) console.error(`  ${o}`);
  }
}
