#!/usr/bin/env node
// Stage 11: line and branch coverage of the unit and integration runs, for the audit pack.
// Runs vitest with v8 coverage over the product's source (not tests, not scripts), writes the HTML
// report to coverage/ and a summary by area to docs/audit/COVERAGE.md. Needs the test database
// (the integration project wipes and migrates DATABASE_URL_TEST). The browser journeys are not
// counted: they run against a separate server process.
//
//   npm run audit:coverage
import { spawnSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';

import * as prettier from 'prettier';

const root = join(import.meta.dirname, '..');
const out = join(root, 'coverage');

const include = [
  'packages/*/src/**/*.{ts,tsx}',
  'packages/db/migrate.mjs',
  'apps/web/{server,actions,screens,lib}/**/*.{ts,tsx}',
  'apps/web/app/**/route.ts',
  'apps/worker/src/**/*.ts',
];
const exclude = ['**/*.test.ts', '**/*.d.ts', '**/fixtures/**'];

const args = [
  'vitest',
  'run',
  '--coverage.enabled',
  '--coverage.provider=v8',
  `--coverage.reportsDirectory=${out}`,
  '--coverage.reporter=json-summary',
  '--coverage.reporter=html',
  '--coverage.all',
  ...include.map((g) => `--coverage.include=${g}`),
  ...exclude.map((g) => `--coverage.exclude=${g}`),
];
const run = spawnSync('npx', args, { cwd: root, stdio: 'inherit' });
if (run.status !== 0) {
  console.error('audit:coverage: the tests failed; COVERAGE.md not written');
  process.exit(run.status ?? 1);
}

const summary = JSON.parse(readFileSync(join(out, 'coverage-summary.json'), 'utf8'));

/** The area a source file belongs to: a package, the worker, or a folder of the web app. */
function areaOf(file) {
  const p = relative(root, file).split('/');
  if (p[0] === 'packages') return `packages/${p[1]}`;
  if (p[0] === 'apps' && p[1] === 'worker') return 'apps/worker';
  if (p[0] === 'apps' && p[1] === 'web') return p[2] === 'app' ? 'apps/web/app (routes)' : `apps/web/${p[2]}`;
  return p.slice(0, 2).join('/');
}

const blank = () => ({ files: 0, lines: [0, 0], branches: [0, 0], functions: [0, 0] });
const areas = new Map();
const files = [];
for (const [file, s] of Object.entries(summary)) {
  if (file === 'total') continue;
  const a = areas.get(areaOf(file)) ?? blank();
  a.files += 1;
  for (const k of ['lines', 'branches', 'functions']) {
    a[k][0] += s[k].covered;
    a[k][1] += s[k].total;
  }
  areas.set(areaOf(file), a);
  files.push({ file: relative(root, file), lines: s.lines });
}

const pct = ([c, t]) => (t === 0 ? '—' : `${((100 * c) / t).toFixed(1)} %`);
const total = summary.total;
const t = (k) => [total[k].covered, total[k].total];

const lines = [
  '# Coverage',
  '',
  'Generated by `npm run audit:coverage`: the unit and integration tests with v8 coverage, over the product source',
  '(packages, the web app’s server code, actions, screens and route handlers, the worker). Tests and scripts are not',
  'counted. The browser journeys (`tests/e2e`) exercise the pages and actions through a separate server process and',
  'are **not** counted here, so the screens and actions read lower than they are tested. The HTML report is written to',
  '`coverage/` (not committed).',
  '',
  `**Overall:** lines ${pct(t('lines'))}, branches ${pct(t('branches'))}, functions ${pct(t('functions'))}.`,
  '',
  '| Area | Files | Lines | Branches | Functions |',
  '| --- | --- | --- | --- | --- |',
  ...[...areas.entries()]
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([name, a]) => `| ${name} | ${a.files} | ${pct(a.lines)} | ${pct(a.branches)} | ${pct(a.functions)} |`),
  '',
  '## Least covered (lines, 20 or more lines long, outside the screens)',
  '',
  'The screens are walked by the browser journeys instead.',
  '',
  '| File | Lines |',
  '| --- | --- |',
  ...files
    .filter((f) => f.lines.total >= 20 && !f.file.startsWith('apps/web/screens/'))
    .sort((a, b) => a.lines.pct - b.lines.pct)
    .slice(0, 25)
    .map((f) => `| \`${f.file}\` | ${f.lines.pct.toFixed(1)} % of ${f.lines.total} |`),
  '',
];
const target = join(root, 'docs/audit/COVERAGE.md');
const config = { ...(await prettier.resolveConfig(target)), filepath: target };
writeFileSync(target, await prettier.format(lines.join('\n'), config));
console.log(`audit:coverage: lines ${pct(t('lines'))}; docs/audit/COVERAGE.md written`);
